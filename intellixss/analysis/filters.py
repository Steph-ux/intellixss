_CHALLENGE_RE = re.compile(
    r"checking your browser|just a moment|enable javascript and cookies|"
    r"cf-challenge|__cf_chl|ddos protection by|verify you are human|captcha",
    re.I,
)

# Strong CSP: HTML sinks cannot execute (no inline script, no eval, no wildcards)
_CSP_INLINE_SAFE = ("'unsafe-inline'", "'unsafe-eval'", "data:", "*")


def _norm_headers(headers: Dict[str, str]) -> Dict[str, str]:
    return {str(k).lower(): str(v).lower() for k, v in (headers or {}).items()}


def detect_waf(
    headers: Optional[Dict[str, str]] = None,
    body: str = "",
    status: Optional[int] = None,
) -> Tuple[List[FilterType], str, List[str]]:
    """Return (filter_types, waf_name, signals)."""
    headers = _norm_headers(headers or {})
    body_l = (body or "").lower()
    found: List[FilterType] = []
    name = ""
    signals: List[str] = []

    for key, ftype, wname in WAF_HEADER_SIGS:
        for hk, hv in headers.items():
            if key in hk or key in hv:
                if ftype not in found:
                    found.append(ftype)
                name = name or wname
                signals.append(f"header:{hk}")

    server = headers.get("server", "")
    for token, ftype, wname in (
        ("cloudflare", FilterType.WAF_CLOUDFLARE, "cloudflare"),
        ("sucuri", FilterType.WAF_SUCURI, "sucuri"),
        ("imperva", FilterType.WAF_IMPERVA, "imperva"),
        ("incapsula", FilterType.WAF_IMPERVA, "imperva"),
        ("bigip", FilterType.WAF_F5_BIG_IP, "f5"),
        ("fortiweb", FilterType.WAF_FORTIWEB, "fortiweb"),
    ):
        if token in server:
            if ftype not in found:
                found.append(ftype)
            name = name or wname
            signals.append(f"server:{token}")

    for sig, ftype, wname in WAF_BODY_SIGS:
        if sig in body_l:
            if ftype not in found:
                found.append(ftype)
            name = name or wname
            signals.append(f"body:{sig[:40]}")

    if status in (403, 406, 429, 503) and found:
        signals.append(f"status:{status}")
    elif status in (403, 406) and not found:
        found.append(FilterType.WAF_GENERIC)
        name = name or "generic"
        signals.append(f"status:{status}")

    return found, name, signals


def analyze_csp(headers: Optional[Dict[str, str]]) -> Optional[_CspInfo]:
    """Interpret a Content-Security-Policy header far enough to know what dies."""
    hnorm = _norm_headers(headers or {})
    raw = hnorm.get("content-security-policy") or hnorm.get("content-security-policy-report-only")
    if not raw:
        return None
    directives: Dict[str, str] = {}
    for part in raw.split(";"):
        part = part.strip()
        if not part:
            continue
        bits = part.split()
        directives[bits[0].lower()] = " ".join(bits[1:]).lower()

    script_src = directives.get("script-src") or directives.get("default-src") or ""
    strict = bool(script_src) and not any(t in script_src for t in _CSP_INLINE_SAFE)
    blocked: List[str] = []
    if strict:
        blocked = [
            "inline <script>",
            "event handlers (on*=)",
            "javascript: URLs",
            "eval()",
        ]
    elif "'unsafe-inline'" not in script_src and script_src:
        # nonce/hash based: inline needs the nonce, handlers are blocked
        blocked.append("event handlers (on*=)")
    return _CspInfo(present=True, strict=strict, directives=directives, blocked_vectors=blocked)


def classify_filters(
    response: str,
    marker: str,
    headers: Optional[Dict[str, str]] = None,
    status: Optional[int] = None,
    original_payload: Optional[str] = None,
) -> Tuple[List[FilterType], BlockDiagnosis]:
    """
    Classify application-level filters and WAF using response body + headers.
    *marker* is the canary/probe expected to reflect.
    """
    filters: List[FilterType] = []
    headers = headers or {}
    body = response or ""

    waf_filters, waf_name, waf_signals = detect_waf(headers, body, status)
    filters.extend(waf_filters)

    # CSP
    csp = analyze_csp(headers)
    if csp is not None:
        filters.append(FilterType.CSP_STRICT if csp.strict else FilterType.CSP)

    diagnosis = BlockDiagnosis(reason=BlockReason.NONE, status=status, signals=list(waf_signals))

    if status == 429:
        diagnosis.reason = BlockReason.RATE_LIMITED
        diagnosis.detail = "HTTP 429 — rate limited; lower -r or wait"
        diagnosis.suggestion = "Reduce request rate (-r 1) or resume later"
        return _unique(filters) or [FilterType.WAF_GENERIC], diagnosis

    if status and status >= 400 and waf_filters:
        diagnosis.reason = BlockReason.WAF_PAGE
        diagnosis.detail = f"WAF {waf_name or 'unknown'} blocked request (HTTP {status})"
        diagnosis.suggestion = _waf_hint(waf_name)
        return _unique(filters), diagnosis

    if status and status >= 400:
        diagnosis.reason = BlockReason.HTTP_STATUS
        diagnosis.detail = f"HTTP {status}"
        if FilterType.WAF_GENERIC not in filters and status in (403, 406):
            filters.append(FilterType.WAF_GENERIC)
        return _unique(filters), diagnosis

    if _CHALLENGE_RE.search(body):
        diagnosis.reason = BlockReason.CHALLENGE
        diagnosis.detail = "Browser challenge / captcha page"
        diagnosis.signals.append("challenge")
        diagnosis.suggestion = "Run with --browser or supply authenticated cookies"
        if not waf_filters:
            filters.append(FilterType.WAF_GENERIC)
        return _unique(filters), diagnosis

    if not marker:
        return _unique(filters) or [FilterType.NO_FILTER], diagnosis

    marker_l = marker.lower()
    body_l = body.lower()

    if marker not in body:
        # Encoding ladder: raw → entity → URL-encoded → stripped
        if html_mod.escape(marker) in body:
            filters.append(FilterType.HTML_ENCODE)
            diagnosis.reason = BlockReason.CHAR_ENCODED
            diagnosis.detail = "Marker HTML-entity encoded (non-executable)"
        elif _url_encoded_forms(marker) and any(f in body for f in _url_encoded_forms(marker)):
            filters.append(FilterType.URL_ENCODE)
            diagnosis.reason = BlockReason.CHAR_ENCODED
            diagnosis.detail = "Marker URL-encoded on output"
        elif marker.replace("<", "").replace(">", "") in body and ("<" in marker or ">" in marker):
            filters.append(FilterType.STRIP_TAGS)
            filters.append(FilterType.BLOCK_ANGLE)
            diagnosis.reason = BlockReason.CHAR_STRIPPED
            diagnosis.detail = "Angle brackets stripped from marker"
        elif marker_l in body_l:
            diagnosis.reason = BlockReason.NONE
            diagnosis.detail = "Marker reflected (case-folded)"
            filters.append(FilterType.NO_FILTER)
        elif _marker_survives_escaped(marker, body):
            # The marker is present but the page inserted its own escape
            # characters inside it — a quote in the payload became ``\'``. The
            # identifier the payload carries is still there, so this is a
            # reflection, not an absence: treating it as missing would drop the
            # very payload that survives the escaping.
            diagnosis.reason = BlockReason.NONE
            diagnosis.detail = "Marker reflected (escaped in place)"
            filters.append(FilterType.NO_FILTER)
        else:
            diagnosis.reason = BlockReason.NO_REFLECTION
            diagnosis.detail = "Marker not reflected in response"
            diagnosis.suggestion = "Try other parameters or an API/JSON endpoint"
        return _unique(filters) or [FilterType.UNKNOWN], diagnosis

    # Marker reflects — check payload-specific filters.
    payload = original_payload or marker
    payload_l = payload.lower()

    if "<script" in payload_l and "<script" not in body_l:
        filters.append(FilterType.STRIP_SCRIPT)
        diagnosis.reason = BlockReason.FILTERED_PAYLOAD
        diagnosis.detail = "script tags stripped while marker survives"
    if re.search(r"on\w+\s*=", payload, re.I) and not re.search(
        r"on\w+\s*=\s*(?:alert|prompt|confirm|eval)", body_l, re.I
    ):
        filters.append(FilterType.STRIP_EVENTS)
        diagnosis.reason = BlockReason.FILTERED_PAYLOAD
        diagnosis.detail = "event handlers stripped"

    if not filters:
        filters.append(FilterType.NO_FILTER)

    if diagnosis.reason == BlockReason.NONE and waf_name:
        diagnosis.detail = f"WAF fingerprint: {waf_name} (request not hard-blocked)"
        diagnosis.signals.append(f"waf_name:{waf_name}")

    return _unique(filters), diagnosis


def _marker_survives_escaped(marker: str, body: str) -> bool:
    """True when *marker* is in *body* with backslashes inserted inside it.

    An app that escapes quotes does so *inside* the reflected value, so the
    marker's own characters become non-adjacent: ``ixm…'`` reads as ``ixm…\\'``.
    Removing every backslash from the response and looking again answers
    "did this identifier come back at all", which is the question this gate is
    actually asking.
    """
    if not marker or "\\" not in body:
        return False
    if marker.lower() in body.replace("\\", "").lower():
        return True
    # A JavaScript-aware escaper writes quotes as ``\u0027``; the interpreter
    # still sees the character, so the identifier survives the escaping.
    import re as _re

    return marker.lower() in _re.sub(
        r"\\u([0-9a-fA-F]{4})",
        lambda m: chr(int(m.group(1), 16)) if int(m.group(1), 16) < 0x110000 else "",
        body,
    ).lower()


def _url_encoded_forms(marker: str) -> List[str]:
    from urllib.parse import quote

    forms = [quote(marker), quote(marker, safe="")]
    return [f for f in forms if f != marker]


def _waf_hint(name: str) -> str:
    hints = {
        "cloudflare": "Try --waf Playbook: encoded eval + mXSS vectors",
        "sucuri": "Sucuri blocks keywords — rely on eval(atob()) payloads",
        "modsecurity": "CRS ruleset — target the eval(atob()) profile",
        "akamai": "Akamai is strict on <script; prefer svg/img handlers",
        "f5": "F5 blocks naive tags — use attribute/newline tricks",
    }
    return hints.get((name or "").lower(), "Escalate to encoding layers (--encodings)")


def _unique(items: List[FilterType]) -> List[FilterType]:
    out: List[FilterType] = []
    for i in items:
        if i not in out:
            out.append(i)
    return out
